#!/usr/bin/env node
/* global console, fetch, setTimeout */
// Generates src/gitlab-openapi.ts, the types the GitLab client is checked
// against, from GitLab's own OpenAPI description:
//
//   1. download the description pinned in spec/gitlab/config.json
//   2. apply spec/gitlab/overlays/*.yaml in order, to fix upstream spec bugs
//   3. keep only the listed operations, then drop unused components
//   4. convert to TypeScript with openapi-typescript
//
// Fails if an overlay matches nothing or a listed operation is missing, so
// upstream fixes and regressions surface here rather than at runtime. Based on
// interforge's scripts/update-specs.ts (https://github.com/benbalter/interforge).
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import {
  openapiFilter,
  openapiOverlay,
  parseFile,
  parseString,
} from 'openapi-format';
import openapiTS, { astToString } from 'openapi-typescript';

const specDir = join('spec', 'gitlab');
const output = join('src', 'gitlab-openapi.ts');
const METHODS = ['get', 'put', 'post', 'delete', 'patch', 'head', 'options'];

const config = JSON.parse(await readFile(join(specDir, 'config.json'), 'utf8'));

// gitlab.com sometimes answers CI runners with 429s, so retry a few times
async function download(url) {
  for (let attempt = 1; ; attempt++) {
    const response = await fetch(url);
    if (response.ok) {
      const doc = await parseString(await response.text(), { format: 'yaml' });
      if (doc instanceof Error) throw doc;
      return doc;
    }
    if (attempt === 4 || (response.status !== 429 && response.status < 500)) {
      throw new Error(`Downloading ${url} failed: ${response.status}`);
    }
    await new Promise((resolve) => setTimeout(resolve, 2 ** attempt * 1000));
  }
}

async function applyOverlays(doc) {
  const dir = join(specDir, 'overlays');
  const files = (await readdir(dir)).filter((f) => /\.ya?ml$/.test(f)).sort();
  for (const file of files) {
    const overlaySet = await parseFile(join(dir, file));
    const { data, resultData } = await openapiOverlay(doc, { overlaySet });
    if (resultData.totalUnusedActions) {
      throw new Error(
        `${file}: ${resultData.totalUnusedActions} action(s) matched nothing. ` +
          'Upstream may have fixed or moved the target.',
      );
    }
    doc = data;
  }
  return doc;
}

// Custom rather than openapi-format's `inverseOperationIds`, which also deletes
// schema properties named after HTTP methods (thim81/openapi-format#238)
function keepOperations(doc) {
  const wanted = new Map();
  for (const operation of config.operations) {
    const [method, path] = operation.split(' ');
    wanted.set(path, (wanted.get(path) ?? new Set()).add(method.toLowerCase()));
  }
  const paths = {};
  for (const [path, methods] of wanted) {
    const item = doc.paths[path] ?? {};
    paths[path] = Object.fromEntries(
      Object.entries(item).filter(
        ([key]) => !METHODS.includes(key) || methods.has(key),
      ),
    );
    for (const method of methods) {
      if (!paths[path][method]) {
        throw new Error(
          `Operation not in description: ${method.toUpperCase()} ${path}`,
        );
      }
    }
  }
  return { ...doc, paths, webhooks: undefined, 'x-webhooks': undefined };
}

let doc = await download(config.source);
doc = await applyOverlays(doc);
doc = keepOperations(doc);
doc = (
  await openapiFilter(doc, {
    filterSet: {
      unusedComponents: [
        'schemas',
        'parameters',
        'responses',
        'requestBodies',
        'headers',
        'examples',
      ],
    },
  })
).data;

// GitLab's description is CC BY-SA 4.0, not MIT like the rest of the repo, so
// say so in the generated file. See NOTICE.
const license = doc.info?.license;
if (!license?.name) {
  throw new Error('Upstream description declares no license');
}
const safe = (s) => s.replace(/\s+/g, ' ').replaceAll('*/', '*\\/');
const header = [
  '/**',
  ` * Generated by script/update-gitlab-types.mjs from ${config.source}`,
  ` * Upstream license: ${safe(license.name)}${license.url ? ` (${safe(license.url)})` : ''}.`,
  ' * Modified: filtered to the operations in spec/gitlab/config.json and',
  ' * patched with spec/gitlab/overlays. See NOTICE.',
  ' * Do not edit by hand. Run `npm run gitlab-types`.',
  ' */',
  '',
].join('\n');
await writeFile(output, header + astToString(await openapiTS(doc)));
console.log(`Wrote ${output} (${config.operations.length} operations)`);
